import { test, expect } from '@playwright/test';

const nav = (page, name) => page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true });
const frame = page => page.locator('#main-content').getByRole('region', { name: 'Shared decision frame', exact: true });
const editFrame = async page => frame(page).getByRole('button', { name: 'Edit decision frame', exact: true }).click();

test('own-decision framing saves and reopens across mobile and workspace changes without replacing existing work', async ({ page }) => {
  await page.goto('/app');
  await expect(nav(page, 'Home')).toBeVisible({ timeout: 45000 });
  await page.evaluate(() => {
    localStorage.setItem('prioritize-workspaces', JSON.stringify([{ id: 'a', name: 'Own A' }, { id: 'b', name: 'Own B' }]));
    localStorage.setItem('prioritize-active-workspace', 'a');
    localStorage.setItem('prioritize-ws-a', JSON.stringify({ features: [{ id: 'keep', name: 'Keep existing candidate', reach: 55, impact: 55, confidence: 20, effort: 35 }], manualOrder: [] }));
    localStorage.setItem('prioritize-ws-a-context', JSON.stringify({ constraints: 'Preserve constraints', scoring: { effortBands: { 35: 'Five person-days' } } }));
    localStorage.setItem('prioritize-ws-b-context', JSON.stringify({ scoring: { decisionQuestion: 'Other workspace question' } }));
  });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/app?start=decision');
  await expect(page.getByLabel('Candidate name', { exact: true })).toBeFocused({ timeout: 45000 });
  await expect(page.getByLabel('Candidate name', { exact: true })).toHaveValue('');
  await frame(page).getByRole('button', { name: 'Edit decision frame', exact: true }).focus();
  await page.keyboard.press('Enter');
  await frame(page).getByLabel('Decision frame: Decision question', { exact: true }).fill('Which response should we test first?');
  await frame(page).getByLabel('Decision frame: Whose problem are we addressing?', { exact: true }).fill('Requesters lack required information; prevalence unknown.');
  await frame(page).getByLabel('Decision frame: Target outcome and baseline', { exact: true }).fill('More complete requests; baseline unknown.');
  await frame(page).getByLabel('Decision frame: Audience unit and size', { exact: true }).fill('Operations requesters; size unknown.');
  await frame(page).getByLabel('Decision frame: Scoring timeframe', { exact: true }).fill('Next 30 days');
  await expect(frame(page).getByText('Context saved in this browser.', { exact: true })).toBeVisible();
  await frame(page).getByRole('button', { name: 'Done editing frame', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('prioritize-ws-a-context')));
  expect(stored.constraints).toBe('Preserve constraints');
  expect(stored.scoring.effortBands['35']).toBe('Five person-days');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('prioritize-ws-a')).features[0].name)).toBe('Keep existing candidate');
  await page.goto('/app?start=decision');
  await expect(page.getByLabel('Candidate name', { exact: true })).toBeFocused();
  await expect(frame(page).getByRole('heading', { name: 'Which response should we test first?' })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByTitle('Own A', { exact: true }).click();
  await page.getByRole('button', { name: 'Switch to workspace: Own B', exact: true }).click();
  await nav(page, 'Home').click();
  await expect(frame(page).getByRole('heading', { name: 'Other workspace question' })).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('prioritize-ws-a-context')).scoring.decisionQuestion)).toBe('Which response should we test first?');
});

test('a partial plan becomes a frozen decision and supplies review/copy context without turning an unknown outcome into success', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => { throw new Error('Use visible copy fallback'); } }, configurable: true }));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/app');
  await expect(nav(page, 'Home')).toBeVisible({ timeout: 45000 });
  await editFrame(page);
  await frame(page).getByLabel('Decision frame: Decision question', { exact: true }).fill('Readiness or reminders?');
  await frame(page).getByLabel('Decision frame: Target outcome and baseline', { exact: true }).fill('Request completeness; baseline unknown');
  // Validate is a Home shortcut on phones, rather than a bottom-nav item.
  await page.locator('#main-content').getByRole('button', { name: 'Validate', exact: true }).click();
  await page.getByLabel('IDEA NAME', { exact: true }).fill('Learn before building');
  await page.getByLabel('Test question or assumption', { exact: true }).fill('Does missing context prevent action?');
  await page.getByLabel('Method', { exact: true }).fill('Paper checklist exercise');
  await page.getByLabel('What would change the choice?', { exact: true }).fill('Revise if complete requests are still overlooked.');
  await page.getByLabel('Test owner', { exact: true }).fill('Test owner');
  await page.getByLabel('Planned test review date', { exact: true }).fill('2026-12-18');
  await page.getByLabel('NEXT VALIDATION ACTIONS', { exact: true }).fill('Preserve free notes; a tentative narrative date is 2026-11-01.');
  await page.getByRole('button', { name: 'Save brief', exact: true }).click();
  await expect(page.getByText('Saved in this browser · Revision 1', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create Decision Draft', exact: true }).click();
  const open = () => page.getByRole('button', { name: 'Decision: Validation: Learn before building', exact: true }).click();
  await open();
  const summary = page.getByRole('region', { name: 'Decision at a glance', exact: true });
  await expect(summary.locator('time')).toHaveAttribute('datetime', '2026-12-18');
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('prioritize-ws-default-decisions'))[0]);
  expect(original.owner).toBe('Test owner');
  expect(original.expected_outcome).toBe('');
  await nav(page, 'Home').click();
  await editFrame(page);
  await frame(page).getByLabel('Decision frame: Decision question', { exact: true }).fill('Changed workspace question');
  await frame(page).getByLabel('Decision frame: Target outcome and baseline', { exact: true }).fill('A different live target; no baseline');
  await nav(page, 'Decisions').click();
  await open();
  await expect(page.getByRole('region', { name: 'Recorded comparison context', exact: true }).getByText('Readiness or reminders?', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Review decision', exact: true }).click();
  const review = page.getByRole('region', { name: 'Decision review', exact: true });
  await expect(review.getByText('Original target outcome and baseline', { exact: true })).toBeVisible();
  await expect(review.getByText('Request completeness; baseline unknown', { exact: true })).toBeVisible();
  await expect(review.getByText('A different live target; no baseline', { exact: true })).toHaveCount(0);
  await expect(review.getByText('Does missing context prevent action?', { exact: true })).toBeVisible();
  await expect(review.getByText('Revise if complete requests are still overlooked.', { exact: true })).toBeVisible();
  await review.getByLabel(/What happened/).fill('Not tested yet; outcome unknown.');
  await review.getByRole('radio', { name: 'Revise', exact: true }).check();
  await review.getByLabel('Revised direction and next action', { exact: true }).fill('Try a smaller paper exercise first.');
  await review.getByRole('button', { name: 'Save review', exact: true }).click();
  await expect(summary.locator('time')).toHaveCount(0);
  await expect(summary.getByRole('definition').filter({ hasText: 'Try a smaller paper exercise first.' })).toBeVisible();
  await page.getByRole('button', { name: 'Copy decision brief', exact: true }).click();
  const copy = page.getByLabel('Decision brief to copy', { exact: true });
  await expect(copy).toHaveValue(/Does missing context prevent action/);
  await expect(copy).toHaveValue(/Next review date: Not scheduled/);
  await expect(copy).toHaveValue(/Not tested yet; outcome unknown/);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('prioritize-ws-default-decisions'))[0]);
  expect(saved.recommendation_snapshot).toEqual(original.recommendation_snapshot);
  expect(saved.reviews[0].decision_snapshot).toEqual(original);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
