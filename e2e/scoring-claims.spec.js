import { test, expect } from '@playwright/test';

test('source-linked claims and targeted answers survive reopening; assumptions remain explicit', async ({ page }) => {
  await page.goto('/app');
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await nav.getByRole('button', { name: 'Signals', exact: true }).click();
  await page.getByRole('button', { name: '+ Add Signal', exact: true }).click();
  await page.getByPlaceholder('Signal title', { exact: true }).fill('Synthetic pilot note');
  await page.getByPlaceholder('Details, quotes, or notes...', { exact: true }).fill('Synthetic exercise: thirty accounts eligible. No real customer measurements.');
  await page.getByRole('button', { name: 'Add Signal', exact: true }).click();
  await nav.getByRole('button', { name: 'Priorities', exact: true }).click();
  await page.getByRole('button', { name: /Add Candidate/i }).first().click();
  await page.getByLabel('Candidate name', { exact: true }).fill('Claim provenance test');
  await page.getByRole('button', { name: 'Add scoring claim', exact: true }).click();
  await page.getByLabel('Claim 1', { exact: true }).fill('Thirty of 100 accounts forecast to use the pilot');
  await page.getByLabel('Claim type for claim 1', { exact: true }).selectOption('estimate');
  await page.getByLabel('Evidence for claim 1', { exact: true }).selectOption({ label: 'Synthetic pilot note' });
  await page.getByLabel('Source relationship 1 for claim 1', { exact: true }).selectOption('supports');
  await page.getByLabel('Excerpt 1 for claim 1', { exact: true }).fill('thirty accounts eligible');
  await expect(page.getByText(/Excerpt matches source/)).toBeVisible();
  const reachCard = page.getByRole('region', { name: 'Reach score', exact: true });
  await reachCard.getByText('Choose recorded basis', { exact: true }).click();
  await expect(page.getByLabel('Recorded basis for reach', { exact: true })).toHaveValue('');
  await page.getByLabel('Recorded basis for reach', { exact: true }).selectOption({ index: 1 });
  await expect(reachCard.getByText('Recorded basis · User estimate', { exact: true })).toBeVisible();
  let requests = 0;
  await page.route('**/api/suggest-scores', async route => {
    const body = route.request().postDataJSON();
    expect(body.scoringBasis.claims[0]).toMatchObject({kind:'estimate',sources:[{relation:'supports',quote:'thirty accounts eligible'}]});
    expect(body.scoringBasis.basisClaimIds).toEqual({reach:body.scoringBasis.claims[0].id});
    const iteration = requests++;
    if (iteration) expect(body.scoringBasis.claims).toEqual(expect.arrayContaining([expect.objectContaining({question:'Is the pilot population 100 accounts?',kind:'estimate'})]));
    const followUp = {question:iteration === 2 ? 'How many accounts are eligible over 90 days rather than 30?' : 'Is the pilot population 100 accounts?',whyItChangesScore:'A different denominator or period changes the reach band.',claimIds:[]};
    const answer = body.scoringBasis.claims.find(claim => claim.question);
    await route.fulfill({json:{reach:{score:35,justification:'Segment band from a forecast',evidence:[],assumptions:['All eligible accounts adopt'],gaps:[],nextAction:'Suggested research: Track unique affected accounts prospectively during the shared scoring period.',claimReviews:[],followUp:iteration === 1 ? null : followUp,...(iteration === 1 ? {followUpResolution:{status:'answered',sourceId:`claim:${answer.id}`,label:'Recorded claim · User estimate',text:answer.text}} : {})}}});
  });
  await page.getByRole('button', { name: '✦ AI Suggest Scores', exact: true }).click();
  await page.getByText('Review reasoning & next question', { exact: true }).click();
  await page.getByLabel('Answer reach follow-up', { exact: true }).fill('100 accounts in this fictional planning cohort; not measured');
  await page.getByRole('button', { name: 'Add answer to draft', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Accept reach suggestion', exact: true })).toBeDisabled();
  await page.getByText('AI assumptions · 1 unverified',{exact:true}).click();
  await page.getByRole('button', { name: 'Add as AI assumption', exact: true }).click();
  await page.getByRole('button', { name: '✦ AI Suggest Scores', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Accept reach suggestion', exact: true })).toBeEnabled();
  await expect(reachCard.getByText('Already in your context',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Answer reach follow-up',{exact:true})).toHaveCount(0);
  await expect(reachCard.getByText('Suggested research: Track unique affected accounts prospectively during the shared scoring period.',{exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', { name: '✦ AI Suggest Scores', exact: true }).click();
  await expect(reachCard.getByText('How many accounts are eligible over 90 days rather than 30?',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Answer reach follow-up',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Add Candidate', exact: true }).click();
  await page.reload();
  await nav.getByRole('button', { name: 'Priorities', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Claim provenance test', exact: true }).click();
  await expect(page.getByLabel('Recorded basis for reach', { exact: true })).not.toHaveValue('');
  await page.getByRole('region', {name:'Scoring claims and sources',exact:true}).locator('summary').getByText('Thirty of 100 accounts forecast to use the pilot',{exact:true}).click();
  await expect(page.getByLabel('Excerpt 1 for claim 1', { exact: true })).toHaveValue('thirty accounts eligible');
  await expect(page.locator('summary').getByText('All eligible accounts adopt',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Reach', { exact: true })).toHaveValue('50');
});
